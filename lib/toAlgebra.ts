import { toAlgebra12Builder } from '@traqula/algebra-sparql-1-2';
import {
  translateAggregates,
  translateBasicGraphPattern,
  translateQuad,
  translateQuery,
  translateTerm,
  Types,
} from '@traqula/algebra-transformations-1-1';
import type * as Trans11 from '@traqula/algebra-transformations-1-1';
import { createAlgebraContext } from '@traqula/algebra-transformations-1-2';
import type {
  Algebra,
  AlgebraIndir,
  ContextConfigs,
  FlattenedTriple,
} from '@traqula/algebra-transformations-1-2';
import { IndirBuilder } from '@traqula/core';
import type * as T11 from '@traqula/rules-sparql-1-1';
import type * as T12 from '@traqula/rules-sparql-1-2';
import type { ConstructTemplate, Query, SparqlQuery } from './types.js';

/**
 * Translates the template of a CONSTRUCT query to the quad patterns of the
 * [CONSTRUCT algebra operation](https://www.w3.org/TR/sparql12-query/#construct).
 * Triples outside `GRAPH` blocks get the default graph, triples within `GRAPH <g> { ... }` get `<g>` as graph,
 * which can also be a variable bound by the WHERE clause.
 */
export const translateConstructTemplate:
AlgebraIndir<'translateConstructTemplate', Algebra.Pattern[], [ConstructTemplate]> = {
  name: 'translateConstructTemplate',
  fun: ({ SUBRULE }) => ({ astFactory: F }, template) => template.flatMap((quads) => {
    const bgp = F.isGraphQuads(quads) ? quads.triples : <T12.PatternBgp> quads;
    const triples: FlattenedTriple[] = [];
    SUBRULE(translateBasicGraphPattern, <T11.BasicGraphPattern> bgp.triples, <Trans11.FlattenedTriple[]> triples);
    if (F.isGraphQuads(quads)) {
      const graph = SUBRULE(translateTerm, quads.graph);
      for (const triple of triples) {
        Object.assign(triple, { graph });
      }
    }
    return triples.map(triple => SUBRULE(translateQuad, <Trans11.FlattenedTriple> triple));
  }),
};

const originalTranslateAggregates = toAlgebra12Builder.getRule(translateAggregates.name);

/**
 * OVERRIDING RULE: {@link translateAggregates}.
 * Wraps the original rule, which translates a CONSTRUCT template of triples:
 * it translates the query with an empty template, after which the quad patterns of the template are filled in.
 */
export const translateAggregatesConstructQuads:
AlgebraIndir<(typeof translateAggregates)['name'], Algebra.Operation, [Query, Algebra.Operation]> = {
  name: translateAggregates.name,
  fun: $ => (C, query, res) => {
    const F = C.astFactory;
    if (!F.isQueryConstruct(query)) {
      return originalTranslateAggregates.fun($)(C, query, res);
    }
    const withoutTemplate = <T12.QueryConstruct> { ...query, template: F.patternBgp([], F.gen()) };
    const result = originalTranslateAggregates.fun($)(C, withoutTemplate, res);
    // The CONSTRUCT operation can be wrapped by a slice or a FROM.
    let operation: Algebra.Operation = result;
    while (operation.type !== Types.CONSTRUCT) {
      if (!('input' in operation) || Array.isArray(operation.input)) {
        throw new Error(`Could not find the ${Types.CONSTRUCT} operation of a CONSTRUCT query`);
      }
      operation = <Algebra.Operation> operation.input;
    }
    operation.template = $.SUBRULE(translateConstructTemplate, query.template);
    return result;
  },
};

/**
 * Pre-configured {@link IndirBuilder} for translating an AST of this extension to SPARQL Algebra.
 * Extends the SPARQL 1.2 algebra builder, translating the quads of CONSTRUCT templates to quad patterns.
 * Use {@link IndirBuilder.create IndirBuilder.create(constructQuadsToAlgebraBuilder)} to extend it.
 */
export const constructQuadsToAlgebraBuilder = IndirBuilder
  .create(toAlgebra12Builder)
  .addRule(translateConstructTemplate)
  .patchRule(translateAggregatesConstructQuads)
  .typePatch<{
    [translateQuery.name]: [Algebra.Operation, [SparqlQuery, boolean | undefined, boolean | undefined]];
  }>();

/**
 * Translates the given query of this extension to SPARQL Algebra.
 * The quads of a CONSTRUCT template become the quad patterns of the CONSTRUCT operation.
 * @param query - AST generated by the parser of this extension.
 * @param options - Optional options object. Current options:
 * @param options.dataFactory - The Datafactory used to generate terms. Default @rdfjs/data-model.
 * @param options.quads - Boolean indicating whether triples should be converted to Quads
 *        (consumes GRAPH statements). Default false.
 * @param options.prefixes - Pre-defined prefixes for the given query. Default empty.
 * @param options.baseIRI - Base IRI that should be used for the query.
 *        Default undefined (throws error if required).
 * @param options.blankToVariable - translate all blank nodes into variables
 * @returns Operation
 */
export function toAlgebra(query: SparqlQuery, options: ContextConfigs = {}): Algebra.Operation {
  const c = createAlgebraContext(options);
  const transformer = constructQuadsToAlgebraBuilder.build();
  return transformer.translateQuery(c, query, options.quads, options.blankToVariable);
}
